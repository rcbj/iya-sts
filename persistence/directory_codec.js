'use strict';
//
// File: persistence/directory_codec.js
//
// ===========================================================================
// A DIRECTORY ENTRY IS STORED SEALED (#391 phase 6, #222, 2026-10-01).
//
// rcbj's decision on #391: each entry's attributes are sealed as ONE blob
// under its realm's `directory` data key — a person's under the home cell's
// where the cell holds a key — in `sts_ldap_entries.attrs`; the DN stays
// readable, and so does every lookup and cross-entry reference that is a DN.
// The lookups that read a VALUE are kept indexed by columns this module
// computes and the service writes (they were generated by the database from
// the plaintext): each a KEYED DIGEST (`keystore.keyedDigest()`, the digest
// key every node holds), so an exact match is still one indexed probe and
// nothing in the column says what it matched.
//
//   name_keys   the `uid` values, lower-cased      — `byName()`
//   mail_keys   `mail`, lower-cased                — `byMail()`
//   uuid_keys   `entryUUID` and its aliases        — `byUuid()`,
//                                                   `withUuids()`
//   class_keys  the GROUP `objectClass` values     — `classesUnder()`
//               (CLASS_INDEXED), lower-cased; none for anything else
//   value_keys  `name=value` of VALUE_INDEXED       — `byAttribute()`
//   attr_names  the attribute NAMES, in the clear  — `withAttribute()`
//
// Attribute names are not a person's data (every person has a `mail`), and
// "who holds a credential of this kind" is a question the windowed directory
// asks of the store, so they stay readable.
//
// **THE BLOB NAMES ITS DN.** What is sealed is `{ "dn": <dn_key>, "a":
// <attributes> }`, and an open refuses a blob whose DN is not its row's: a
// blob copied onto another entry's row does not open as that entry.
//
// **WHERE NOTHING DURABLE SEALS, NOTHING IS SEALED** — development, a key that
// dies with the process: the attributes go in as the JSON object they always
// were, and the lookup columns hold `<kind>\n<value>` in the clear (a digest
// needs a key). Every reader takes either shape, so the two can meet
// in one table during a test.
//
// THE QUERIES' TWO HALVES ARE HERE, NOT IN `directory_queries.js`: a question
// is BUILT and its rows turned into entries on whatever thread asks the
// database — the bridge's has no keystore — so a value to look up is keyed
// HERE first (`keyArgs()`) and an answer opened HERE after (`openAnswer()`),
// on the thread that holds the keys.
// ===========================================================================

const bunyan = require('bunyan');

const log = bunyan.createLogger({ name: 'sts-directory-codec' });

const LABEL = 'directory';
const DIGEST_LABEL = 'directory-index';

// The attributes whose values `byAttribute()` looks up — as written, not
// lower-cased, because those lookups compare a value exactly (a DID, a SPIFFE
// ID, a certificate subject, a login name, a federation link).
//
// **AND THE FOUR A DEVICE IS RECOGNISED BY (#636, 2026-10-14)**: a device's
// derived key thumbprint, its Native SSO secret's hash, a linked WebAuthn
// credential's id, and its `owner` (the DN of the person or application that
// owns it). `ldap_server.js`'s `deviceEntryByIndex()` and
// `deviceEntriesOwnedBy()` ask them in a windowed process, where until #636
// recognition built an index by walking `ou=devices` — on a token request,
// through the synchronous bridge, and a `page()` under `ou=devices` reads the
// realm's keys past the last device, so it cost the whole directory however
// few devices there were. `owner` is also on a group or a service account;
// the callers keep the rows under `ou=devices`. A row written before #636
// carries none of the four until it is next written, and nothing migrates
// it (rcbj: every install is rebuilt).
const VALUE_INDEXED = ['uid', 'didsubject', 'spiffesubject', 'x509subject',
                       'federationlink', 'stsdevicekeythumbprint',
                       'stsdevicesecrethash', 'stsdevicecredentialid',
                       'owner'];

// THE OBJECT CLASSES `class_keys` HOLDS: THE GROUP CLASSES, AND ONLY THOSE
// (#618 phase 2, schema version 18). `classesUnder()` is the one question
// asked of the column, and it is only ever asked for a group class
// (`ldap_server.js`'s GROUP_CLASSES, which `tests/directory_queries.js` holds
// to this list): "the groups placed under `ou=users` or `ou=devices`". Until
// version 18 the column held every class, so every person wrote four GIN
// entries — `top`, `person`, `organizationalPerson`, `inetOrgPerson`, each
// in more than 99% of 8081's rows — that narrowed nothing. A person now
// writes `[]`, which the partial index leaves out. An entry written before
// version 18 still holds all its classes until it is next written, and the
// question answers the same over either: a group class is in both.
//
// The database cannot narrow the column itself — each value is a keyed
// digest it cannot read — which is why this is done where the digests are
// made rather than by a generated column or an index expression.
const CLASS_INDEXED = Object.freeze(['groupofnames', 'groupofuniquenames',
                                     'posixgroup', 'groupofurls']);

function keystore() {
  log.debug("Entering keystore().");
  log.debug("Leaving keystore().");
  return require('../common/keystore');
}

// Whether values written now are sealed: a durable key-encryption key.
function sealing() {
  log.debug("Entering sealing().");
  const ks = keystore();
  log.debug("Leaving sealing().");
  return ks.persists() && ks.sealed();
}

/**
 * The lookup form of one value: its keyed digest under `kind`, or the value
 * itself where no digest key is held.
 *
 * @param kind - what the value is (`name`, `mail`, `uuid`, `class`, or
 *   `attr:<name>`)
 * @param value - the value, already in its compared form
 * @returns the column value
 */
function lookupOf(kind, value) {
  log.debug("Entering lookupOf().");
  const text = String(value == null ? '' : value);
  // DIGESTED ON THE SAME CONDITION THE BLOB IS SEALED: a durable key. A
  // per-run key would write digests the next run cannot reproduce, against
  // rows that outlive it.
  const ks = keystore();
  const digest = sealing() && typeof ks.keyedDigest === 'function'
    ? ks.keyedDigest(DIGEST_LABEL, String(kind) + '\n' + text) : null;
  log.debug("Leaving lookupOf().");
  // Without a key the KIND still goes in front, so that one value of two
  // attributes (a `uid` and a `federationlink` both "x") are two lookups.
  return digest || (String(kind) + '\n' + text);
}

// The values of an attribute, by name in any case, as an array of strings.
function valuesOf(attrs, name) {
  log.debug("Entering valuesOf().");
  const out = [];
  Object.keys(attrs || {}).forEach(function (key) {
    if (key.toLowerCase() !== name) {
      return;
    }
    const v = attrs[key];
    (Array.isArray(v) ? v : [v]).forEach(function (one) {
      if (one !== null && one !== undefined) {
        out.push(String(one));
      }
    });
  });
  log.debug("Leaving valuesOf().");
  return out;
}

function lowered(list) {
  log.debug("Entering lowered().");
  log.debug("Leaving lowered().");
  return list.map(function (one) {
    return one.toLowerCase();
  });
}

function unique(list) {
  log.debug("Entering unique().");
  log.debug("Leaving unique().");
  return Array.from(new Set(list));
}

/**
 * The lookup columns of an entry's attributes.
 *
 * @param attrs - the attributes, plaintext
 * @returns `{ nameKeys, mailKeys, uuidKeys, classKeys, valueKeys, attrNames }`
 */
function indexOf(attrs) {
  log.debug("Entering indexOf().");
  const a = attrs || {};
  const keyed = function (kind, list) {
    return unique(list).map(function (one) {
      return lookupOf(kind, one);
    });
  };
  const valueKeys = [];
  VALUE_INDEXED.forEach(function (name) {
    unique(valuesOf(a, name)).forEach(function (one) {
      valueKeys.push(lookupOf('attr:' + name, one));
    });
  });
  const out = {
    nameKeys: keyed('name', lowered(valuesOf(a, 'uid'))),
    mailKeys: keyed('mail', lowered(valuesOf(a, 'mail'))),
    uuidKeys: keyed('uuid', lowered(valuesOf(a, 'entryuuid')
      .concat(valuesOf(a, 'stsentryuuidalias')))),
    classKeys: keyed('class', lowered(valuesOf(a, 'objectclass'))
      .filter(function (one) {
        return CLASS_INDEXED.indexOf(one) >= 0;
      })),
    valueKeys: valueKeys,
    attrNames: unique(Object.keys(a).map(function (one) {
      return one.toLowerCase();
    }))
  };
  log.debug("Leaving indexOf().");
  return out;
}

// A value sealed under a data key: `$aesgcm$2$<dek id>$…` or the same with
// `aessiv` (persistence_postgres.js's SEALED_VALUE, which re-seals by it).
const SEALED_VALUE = /\$aes(?:gcm|siv)\$2\$[A-Za-z0-9_.-]+\$[A-Za-z0-9+/=]*\$[A-Za-z0-9+/=]*\$[A-Za-z0-9+/=]*/g;

/**
 * The data keys an entry holds values under, for `sts_ldap_entries.dek_keys`
 * (#623): `{ <dek id>: <values> }` — the stored blob's own key, once, and the
 * key of every value sealed INSIDE the attributes, once per value. What the
 * re-encryption job finds an entry by and what `sts_ldap_dek_counts` sums,
 * so it counts what the directory walk it replaced counted.
 *
 * @param attrs - the attributes as text (their JSON) or as an object; a
 *   blob that did not open is passed as null and counts for its own key only
 * @param stored - the `attrs` column value: the sealed blob, or the plain
 *   attributes where nothing seals
 * @returns the map, `{}` for an entry holding nothing sealed
 */
function dekKeysOf(attrs, stored) {
  log.debug("Entering dekKeysOf().");
  const out = {};
  const add = function (id) {
    if (id) {
      out[id] = (out[id] || 0) + 1;
    }
  };
  if (typeof stored === 'string') {
    add(require('../common/crypto').dekIdOf(stored));
  }
  const text = typeof attrs === 'string' ? attrs
    : (attrs === null || attrs === undefined ? '' : JSON.stringify(attrs));
  (text.match(SEALED_VALUE) || []).forEach(function (one) {
    add(one.split('$')[3]);
  });
  log.debug("Leaving dekKeysOf().");
  return out;
}

/**
 * Builds the codec one driver uses: `tier` is the data-key tier its entries
 * are sealed under — `cell` for a store of people (a cell's own database, or
 * the one database of a single-cell service, where `cell` is the service's
 * key), `service` for the global tier.
 *
 * @param tier - `cell` or `service`
 * @returns the codec
 */
function create(tier) {
  log.debug("Entering create(). " + tier);
  const codecTier = tier === 'service' ? 'service' : 'cell';
  const codec = {
    tier: codecTier,
    /**
     * The `attrs` column value for an entry: the sealed blob (a JSON string)
     * or the attributes themselves.
     */
    sealAttributes: function (realmId, dnKey, attrs) {
      log.debug("Entering codec.sealAttributes().");
      if (!sealing()) {
        log.debug("Leaving codec.sealAttributes(). Not sealing.");
        return attrs || {};
      }
      const blob = keystore().seal(JSON.stringify({ dn: String(dnKey),
                                                    a: attrs || {} }),
                                   LABEL, codecTier,
                                   { realm: String(realmId || '') });
      log.debug("Leaving codec.sealAttributes().");
      return blob;
    },
    /**
     * The attributes from an `attrs` column value, or null for a blob that
     * does not open or names another DN.
     */
    openAttributes: function (dnKey, stored) {
      log.debug("Entering codec.openAttributes().");
      if (stored === null || stored === undefined) {
        log.debug("Leaving codec.openAttributes(). Nothing.");
        return {};
      }
      if (typeof stored !== 'string') {
        log.debug("Leaving codec.openAttributes(). Plain.");
        return stored;
      }
      const text = keystore().open(stored, LABEL);
      if (text === null || text === undefined) {
        log.debug("Leaving codec.openAttributes(). Does not open.");
        return null;
      }
      let parsed = null;
      try {
        parsed = JSON.parse(text);
      } catch (e) {
        log.debug("Caught in codec.openAttributes(): " +
                  ((e && e.message) || e));
        parsed = null;
      }
      if (!parsed || typeof parsed !== 'object' ||
          (dnKey !== undefined && dnKey !== null &&
           String(parsed.dn) !== String(dnKey))) {
        log.debug("Leaving codec.openAttributes(). Not this entry's.");
        return null;
      }
      log.debug("Leaving codec.openAttributes().");
      return parsed.a || {};
    },
    index: indexOf,
    dekKeys: dekKeysOf
  };
  log.debug("Leaving create().");
  return codec;
}

/**
 * A query's arguments with every value it looks up turned into its lookup
 * form, for the thread that builds the statement (`directory_queries.js`).
 *
 * @param name - the query's name
 * @param args - its arguments as the directory asks them
 * @returns the arguments the builder takes
 */
function keyArgs(name, args) {
  log.debug("Entering keyArgs(). " + name);
  const a = Array.isArray(args) ? args.slice() : [];
  const lower = function (v) {
    return String(v == null ? '' : v).trim().toLowerCase();
  };
  if (name === 'byName') {
    const wanted = lower(a[2]);
    a[2] = { key: lookupOf('name', wanted), rdn: wanted };
  } else if (name === 'withNames') {
    a[2] = (a[2] || []).map(function (one) {
      const wanted = lower(one);
      return { key: lookupOf('name', wanted), rdn: wanted };
    });
  } else if (name === 'byUuid') {
    a[1] = { key: lookupOf('uuid', lower(a[1])) };
  } else if (name === 'withUuids') {
    a[1] = (a[1] || []).map(function (one) {
      return { key: lookupOf('uuid', lower(one)) };
    });
  } else if (name === 'byMail') {
    a[1] = { key: lookupOf('mail', lower(a[1])) };
  } else if (name === 'equalUnder') {
    a[3] = { key: lookupOf(String(a[2]), lower(a[3])) };
  } else if (name === 'byAttribute') {
    // An attribute `value_keys` does not hold would be answered "nobody" by
    // a question that looks right — `classesUnder`'s reason, below (#636).
    if (VALUE_INDEXED.indexOf(lower(a[1])) < 0) {
      log.debug("Leaving keyArgs(). An attribute that is not indexed.");
      throw new Error('directory_codec: byAttribute is asked only for the ' +
                      'value-indexed attributes (' +
                      VALUE_INDEXED.join(', ') + '), not ' + lower(a[1]));
    }
    a[2] = { key: lookupOf('attr:' + lower(a[1]), String(a[2])) };
  } else if (name === 'classesUnder') {
    a[2] = (a[2] || []).map(function (one) {
      const wanted = lower(one);
      // A class the column does not hold would be answered "nobody" by a
      // question that looks right, so it is refused where it is asked.
      if (CLASS_INDEXED.indexOf(wanted) < 0) {
        log.debug("Leaving keyArgs(). A class that is not indexed.");
        throw new Error('directory_codec: classesUnder is asked only for ' +
                        'the group classes (' + CLASS_INDEXED.join(', ') +
                        '), not ' + wanted);
      }
      return { key: lookupOf('class', wanted) };
    });
  }
  log.debug("Leaving keyArgs().");
  return a;
}

/**
 * A query's answer with every entry's attributes opened, on the thread that
 * holds the keys. A row whose blob does not open is dropped with a warning:
 * an entry this process cannot read is one it cannot answer about.
 *
 * @param codec - the driver's codec
 * @param name - the query's name
 * @param answer - what `directory_queries.answerOf()` gave
 * @returns the answer
 */
function openAnswer(codec, name, answer) {
  log.debug("Entering openAnswer(). " + name);
  // KEYS AND DNs ONLY (`keysUnder`, #616): nothing sealed to open.
  if (!Array.isArray(answer) || name === 'keysUnder') {
    log.debug("Leaving openAnswer(). Not entries.");
    return answer;
  }
  const out = [];
  answer.forEach(function (row) {
    if (name === 'namesUnder') {
      const attrs = codec.openAttributes(row.key, row.attrs);
      const uid = attrs ? valuesOf(attrs, 'uid')[0] || '' : '';
      out.push({ key: row.key, dn: row.dn, origin: row.origin,
                 uid: row.uid || uid });
      return;
    }
    const attrs = codec.openAttributes(row.key, row.entry &&
                                       row.entry.attributes);
    if (attrs === null) {
      log.warn(require('../common/error_codes').tag('STS-STORE-0072') +
               'persistence: the directory entry ' + row.key + ' in the "' +
               row.realm + '" realm is sealed and did not open here; it is ' +
               'left out of the answer.');
      return;
    }
    out.push(Object.assign({}, row, { entry: Object.assign({}, row.entry,
                                                           { attributes:
                                                             attrs }) }));
  });
  log.debug("Leaving openAnswer().");
  return out;
}

