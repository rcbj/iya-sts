/**
 * Builds a named query.
 *
 * @param name - one of the names in `QUERIES`
 * @param args - its arguments, in order
 * @returns the statement
 * @throws an Error naming an unknown query
 */
function build(name, args) {
  log.debug("Entering build().");
  const f = Object.prototype.hasOwnProperty.call(QUERIES, name)
    ? QUERIES[name] : null;
  if (!f) {
    log.debug("Leaving build(). Unknown.");
    throw new Error('directory_queries: no query called ' + String(name));
  }
  log.debug("Leaving build().");
  return f.apply(null, Array.isArray(args) ? args : []);
}

