//
// File: persistence/bulk_import.js
//
// ===========================================================================
// PEOPLE FROM AN LDIF FILE, INTO THE STORE, THOUSANDS A SECOND (#629,
// 2026-10-14).
//
//   node persistence/bulk_import.js --file=people.ldif [--realm=<id>]
//        [--batch=5000] [--skip=<records>] [--report=<file.json>]
//
// run inside the service's image, configured EXACTLY LIKE THE SERVICE (the
// same CONFIG_FILE and environment), WITH THE SERVICE STOPPED. Every one of
// the database URL, its password provider and TLS, and the key-encryption
// key is read through the service's own code (`persistence.
// databaseConnection()`, `persistence_postgres.create()` and `open()`,
// `keystore.start()`), as `cell_convert.js` does, so the tool cannot dial a
// database or seal under a key the service would not.
//
// **WHY A DOOR AT ALL.** An LDAP add is a protocol round trip, two claims, a
// flush transaction, change-log rows and a replication to every process:
// hundreds a second at best, and 200 million people at 70 a second is a
// month. This is one set-based INSERT per batch of thousands.
//
// **WHY OFFLINE** (rcbj on #629, the design comment there): a running
// process holds ABSENCES in its directory window, and a whole-directory
// process would see none of these rows without one change row per entry —
// two hundred million rows in `sts_changes`. Every process that starts after
// the import reads the tables as they are, so offline needs no second
// mechanism. A service that is running is REFUSED (STS-LDAP-0153): every
// process with a postgres store reports into `sts_change_readers` every 15 s,
// and a clean stop deletes its row; asked before the first batch and before
// every one after it.
//
// **WHAT A ROW IS, EXACTLY: WHAT AN LDAP ADD BY AN ADMIN WRITE BINDER WRITES**
// (`ldapAddNow()` -> `putEntry()` -> the flush's `entryParams()`):
//
//   * the record's attributes, names lower-cased, values arrays of strings,
//     in the record's order; then `createtimestamp` and `modifytimestamp`
//     (generalized time, also `created_at` / `modified_at`); then
//     `preferredlanguage` and `stspreferredlanguagepopulated` where the
//     realm's locale policy populates and the record names none
//     (`fillPreferredLanguage()`); then `entryuuid`, a random v4; then
//     `stsmailverified`, the first `mail` — an operator holding the store is a
//     trusted source, as `ldap-admin` is (`verifyWrittenMail()`);
//   * origin `bulk import`, so `/admin/ldap/directory` counts what each door
//     made;
//   * `attrs` sealed by `directory_codec.sealAttributes()` under the realm's
//     current `directory` data key, the six lookup columns by its `index()`
//     and `dek_keys` by its `dekKeys()` — the calls `entryParams()` makes;
//   * `parent_key` and `rdn_value` generated by the database; the #618 and
//     #623 counters kept by their statement-level triggers, which one
//     INSERT … SELECT fires once with every inserted row in `new_rows`.
//
// **ONE ENTRY PER PERSON, AS `existingUserEntry()` ASKS IT.** A record's
// names are its RDN value and every `uid`, lower-cased; one is HELD when an
// entry directly under `ou=users` has its keyed digest in `name_keys` or it
// as `rdn_value` — `directory_queries.byName()`'s WHERE clause, asked for
// every name of every record in one statement. Within a batch the first
// record wins (in JavaScript); across batches the earlier batch is
// committed, so the store answers. A record whose DN is already there is
// PRESENT and skipped, which is what makes a re-run add nothing.
//
// **WHAT IT DOES NOT DO**, each argued on #629 and in `docs/bulk-import.md`:
// no credentials (a password, Kerberos keys, a factor — the allowlist below
// refuses every one), no audit row per entry, no `noteAccountChange()` (so no
// RISC or CAEP event and no outbound SCIM push), no groups, no update of an
// existing entry, no multi-cell store (the routing index), no ldif store.
// ===========================================================================

