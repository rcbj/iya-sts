/**
 * A DN as a comparison key: each RDN trimmed and lower-cased. The rule of
 * `ldap/ldap_server.js`'s `normalizeDn()`, spelt again because requiring that
 * file would load the directory; `tests/bulk_import.js` compares the two.
 * A HOT PATH (several times a record), so no Entering/Leaving pair.
 *
 * @param value - the DN
 * @returns the key
 */
function normalizeDn(value) {
  const text = String(value == null ? '' : value).trim();
  return text.split(',').map(function (part) {
    return part.trim().toLowerCase();
  }).join(',');
}

/**
 * `YYYYMMDDHHMMSSZ`, `ldap_server.js`'s `generalizedTime()`.
 *
 * @param when - the instant
 * @returns the generalized time
 */
function generalizedTime(when) {
  log.debug("Entering generalizedTime().");
  const d = when instanceof Date ? when : new Date();
  const pad = function (n, width) {
    log.debug("Entering pad().");
    log.debug("Leaving pad().");
    return String(n).padStart(width || 2, '0');
  };
  log.debug("Leaving generalizedTime().");
  return pad(d.getUTCFullYear(), 4) + pad(d.getUTCMonth() + 1) +
    pad(d.getUTCDate()) + pad(d.getUTCHours()) + pad(d.getUTCMinutes()) +
    pad(d.getUTCSeconds()) + 'Z';
}

// An Error carrying its code, for a refusal of the whole run.
function refusal(code, message) {
  log.debug("Entering refusal(). " + code);
  const e = errorCodes.mark(new Error(errorCodes.tag(code) + 'bulk_import: ' +
                                      message), code);
  log.debug("Leaving refusal().");
  return e;
}

/**
 * Checks one parsed LDIF record and turns it into a candidate, or says why
 * not. A HOT PATH (once a record), so no Entering/Leaving pair.
 *
 * @param record - `ldif_stream`'s record
 * @param usersKey - the realm's `ou=users` DN, normalised
 * @param required - the attributes the realm's attribute policy requires,
 *   lower-cased, where it is enforced (#396); empty where it is not
 * @returns `{ ok: true, dn, dnKey, names, attributes }` or
 *   `{ ok: false, code, reason }`
 */
function candidateOf(record, usersKey, required) {
  const entry = record.entry || {};
  // A refusal's shape. A hot path's helper, so no Entering/Leaving pair.
  const no = function (code, reason) {
    return { ok: false, code: code, reason: reason };
  };
  if (record.url) {
    return no('STS-LDAP-0156', 'a value is a URL reference (name:< url), ' +
              'which this service does not dereference');
  }
  if (record.extra) {
    return no('STS-LDAP-0155', 'the block holds more than one dn: (a blank ' +
              'line between records is missing)');
  }
  const parts = String(entry.dn || '').split(',').map(function (one) {
    return one.trim();
  });
  const dn = parts.join(',');
  if (normalizeDn(parts.slice(1).join(',')) !== usersKey) {
    return no('STS-LDAP-0155', 'the DN ' + dn + ' is not directly under ' +
              'the realm\'s ou=users');
  }
  const rdn = parts[0];
  const eq = rdn.indexOf('=');
  if (eq < 0 || rdn.slice(0, eq).trim().toLowerCase() !== 'uid' ||
      /[\\+"]/.test(rdn)) {
    return no('STS-LDAP-0155', 'the RDN ' + rdn + ' is not a plain uid=<name> ' +
              '(no escape, no +)');
  }
  const rdnValue = rdn.slice(eq + 1).trim();
  if (!rdnValue) {
    return no('STS-LDAP-0155', 'the RDN names nobody');
  }
  const attrs = entry.attributes || {};
  const attributes = {};
  const names = Object.keys(attrs);
  if (names.indexOf('changetype') >= 0) {
    const kind = (attrs.changetype || []).join(',').trim().toLowerCase();
    if (kind !== 'add') {
      return no('STS-LDAP-0156', 'changetype ' + kind + ' is not an add');
    }
  }
  for (const name of names) {
    if (name === 'changetype') {
      continue;
    }
    if (!ALLOWED_ATTRIBUTES.has(name)) {
      return no('STS-LDAP-0156', 'the attribute ' + name + ' is not one a ' +
                'bulk import may carry (a credential, an operational or ' +
                'service attribute, or not a person\'s)');
    }
    const values = (attrs[name] || []).map(String);
    for (const value of values) {
      if (value === '' || value.indexOf('\u0000') >= 0) {
        return no('STS-LDAP-0156', 'a value of ' + name + ' is empty or ' +
                  'carries a NUL byte');
      }
    }
    attributes[name] = values;
  }
  const classes = (attributes.objectclass || []).map(function (one) {
    return one.trim().toLowerCase();
  });
  if (!classes.length || classes.some(function (one) {
    return !PERSON_CLASSES.has(one);
  })) {
    return no('STS-LDAP-0156', 'objectClass must be among top, person, ' +
              'organizationalPerson and inetOrgPerson');
  }
  const uids = (attributes.uid || []).map(function (one) {
    return one.trim().toLowerCase();
  });
  const wanted = rdnValue.toLowerCase();
  if (uids.indexOf(wanted) < 0) {
    return no('STS-LDAP-0155', 'the uid values do not include the RDN ' +
              'value ' + rdnValue);
  }
  // WHAT THE REALM'S ATTRIBUTE POLICY REQUIRES (#396), in product mode, as
  // an LDAP add is held to it: nothing is derived, the record says what it
  // says. The names are the realm's, read once by `requirementFor()`.
  const missing = (required || []).filter(function (name) {
    return !(attributes[name] || []).some(function (one) {
      return String(one).trim() !== '';
    });
  });
  if (missing.length) {
    return no('STS-LDAP-0163', 'the realm\'s attribute policy requires ' +
              missing.join(', ') + ', which the record does not carry');
  }
  return { ok: true, dn: dn, dnKey: normalizeDn(dn),
           names: Array.from(new Set([wanted].concat(uids))),
           attributes: attributes };
}

/**
 * The stored entry a candidate becomes: `putEntry()`'s attributes, in its
 * order. A HOT PATH (once a record), so no Entering/Leaving pair.
 *
 * @param candidate - `candidateOf()`'s answer
 * @param now - the generalized time to stamp
 * @param language - the locale policy's tag for a new person, or ''
 * @param uuid - the entryUUID
 * @returns `{ dn, attributes, origin, createdAt, modifiedAt }`
 */
function storedOf(candidate, now, language, uuid) {
  const attributes = {};
  Object.keys(candidate.attributes).forEach(function (name) {
    attributes[name] = candidate.attributes[name].slice(0);
  });
  attributes.createtimestamp = [now];
  attributes.modifytimestamp = [now];
  if (language && !(attributes.preferredlanguage || []).length) {
    attributes.preferredlanguage = [language];
    attributes.stspreferredlanguagepopulated = [language];
  }
  attributes.entryuuid = [uuid];
  const mail = String((attributes.mail || [])[0] || '').trim();
  if (mail) {
    attributes.stsmailverified = [mail];
  }
  return { dn: candidate.dn, attributes: attributes, origin: ORIGIN,
           createdAt: now, modifiedAt: now };
}

