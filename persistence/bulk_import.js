const USAGE = 'Usage: node persistence/bulk_import.js --file=<people.ldif> ' +
  '[--realm=<id>] [--batch=<1..' + MAX_BATCH + '>] [--skip=<records>] ' +
  '[--report=<file.json>]';

/**
 * The arguments, or null (and the usage, STS-LDAP-0150) when they are wrong.
 *
 * @param argv - the arguments after the script
 * @returns the options, or null
 */
function optionsOf(argv) {
  log.debug("Entering optionsOf().");
  const out = { file: '', realm: '', batch: DEFAULT_BATCH, skip: 0,
                report: '' };
  const bad = function (why) {
    log.debug("Entering bad().");
    log.debug("Leaving bad().");
    process.stderr.write(errorCodes.tag('STS-LDAP-0150') + 'bulk_import: ' +
                         why + '. ' + USAGE + '\n');
    return null;
  };
  for (const arg of argv) {
    const m = /^--(file|realm|batch|skip|report)=(.*)$/.exec(arg);
    if (!m) {
      log.debug("Leaving optionsOf(). Unknown.");
      return bad('unknown argument "' + arg + '"');
    }
    out[m[1]] = m[2];
  }
  if (!out.file) {
    log.debug("Leaving optionsOf(). No file.");
    return bad('--file is required');
  }
  const batch = Number(out.batch);
  const skip = Number(out.skip);
  if (!Number.isInteger(batch) || batch < 1 || batch > MAX_BATCH ||
      !Number.isInteger(skip) || skip < 0) {
    log.debug("Leaving optionsOf(). A number.");
    return bad('--batch must be 1 to ' + MAX_BATCH + ' and --skip a whole ' +
               'number');
  }
  out.batch = batch;
  out.skip = skip;
  log.debug("Leaving optionsOf().");
  return out;
}

// The settings the import needs, checked before anything is dialled.
function checkSettings() {
  log.debug("Entering checkSettings().");
  const config = require('../common/config');
  if (config.value('persistence.mode') !== 'postgres') {
    throw refusal('STS-LDAP-0151', 'persistence.mode is "' +
                  config.value('persistence.mode') + '": the import writes ' +
                  'a postgres store.');
  }
  if (String(config.value('persistence.globalDatabaseUrl') || '').trim() ||
      require('../common/cells').isMulti()) {
    throw refusal('STS-LDAP-0151', 'this service is deployed as cells, and ' +
                  'a person there is claimed in the global routing index, ' +
                  'which the import does not write.');
  }
  log.debug("Leaving checkSettings().");
}

// The driver's key functions, as `persistence.js` hands them to the
// keystore, so a data key the import makes is written as the service writes
// one (a union under the row's lock, with its change row).
function keystoreHooks(driver) {
  log.debug("Entering keystoreHooks().");
  const hooks = {
    loadKeys: function () {
      log.debug("Entering loadKeys().");
      log.debug("Leaving loadKeys().");
      return driver.loadKeys();
    },
    saveKeys: function (realmId, ciphertext) {
      log.debug("Entering saveKeys().");
      log.debug("Leaving saveKeys().");
      return driver.saveKeys(realmId, ciphertext);
    },
    deleteKeys: function (realmId) {
      log.debug("Entering deleteKeys().");
      log.debug("Leaving deleteKeys().");
      return driver.deleteKeys(realmId);
    },
    loadKey: function (realmId) {
      log.debug("Entering loadKey().");
      log.debug("Leaving loadKey().");
      return driver.loadKey(realmId);
    },
    mergeKeys: function (realmId, ciphertext, merge) {
      log.debug("Entering mergeKeys().");
      log.debug("Leaving mergeKeys().");
      return driver.mergeKeys(realmId, ciphertext, merge);
    }
  };
  log.debug("Leaving keystoreHooks().");
  return hooks;
}

// The realm, defined in this process from its stored row where it is not the
// default, and the base DN its directory is rooted at.
async function holdRealm(db, realmId) {
  log.debug("Entering holdRealm(). " + realmId);
  const realms = require('../common/realms');
  if (!realmId || realmId === realms.DEFAULT_ID) {
    log.debug("Leaving holdRealm(). The default realm.");
    return { record: realms.get(realms.DEFAULT_ID),
             base: realms.baseDnOf(realms.DEFAULT_ID) };
  }
  const r = await db.query('SELECT id, name, description, domain, ' +
                           'overrides FROM sts_realms WHERE id = $1',
                           [realmId]);
  const row = (r.rows || [])[0];
  if (!row) {
    throw refusal('STS-LDAP-0154', 'the store holds no realm "' + realmId +
                  '".');
  }
  if (!realms.get(realmId)) {
    const made = realms.create({ id: row.id, name: row.name,
                                 description: row.description,
                                 domain: row.domain,
                                 overrides: row.overrides || {},
                                 restored: true });
    if (!made.ok) {
      throw refusal('STS-LDAP-0154', 'the realm "' + realmId + '" could not ' +
                    'be read: ' + (made.errors || []).join(' '));
    }
  }
  log.debug("Leaving holdRealm().");
  return { record: realms.get(realmId), base: realms.baseDnOf(realmId) };
}

// The language a NEW person in the realm is given (`fillPreferredLanguage()`),
// from the realm's `ou=localePolicies` entries in the store and the default
// realm's, which `cn=default` is inherited from.
async function languageFor(db, codec, realm, base) {
  log.debug("Entering languageFor().");
  const realms = require('../common/realms');
  const localePolicy = require('../common/locale_policy');
  const held = new Map();
  const read = async function (id, baseDn) {
    log.debug("Entering read(). " + id);
    const parent = normalizeDn('ou=localePolicies,' + baseDn);
    const r = await db.query('SELECT dn_key, dn, attrs FROM ' +
                             'sts_ldap_entries WHERE realm = $1 AND ' +
                             'parent_key = $2', [id, parent]);
    held.set(id, (r.rows || []).map(function (row) {
      const attrs = codec.openAttributes(row.dn_key, row.attrs) || {};
      return { dn: row.dn, attributes: attrs,
               name: (attrs.cn || [])[0] ||
                     String(row.dn).split(',')[0].replace(/^cn=/i, '') };
    }));
    log.debug("Leaving read().");
  };
  await read(realm.id, base);
  if (realm.id !== realms.DEFAULT_ID) {
    await read(realms.DEFAULT_ID, realms.baseDnOf(realms.DEFAULT_ID));
  }
  localePolicy.setDirectory({
    allLocalePolicies: function () {
      log.debug("Entering allLocalePolicies().");
      log.debug("Leaving allLocalePolicies().");
      return held.get(realms.currentId()) || [];
    }
  });
  const tag = realms.run(realm, function () {
    return localePolicy.populationFor('');
  });
  log.debug("Leaving languageFor(). " + (tag || 'none'));
  return tag;
}

// What a NEW person in the realm must carry (#396): the realm's attribute
// policy, from its `ou=attributePolicies` and `ou=attributeDefinitions` rows
// in the store and the default realm's profile it inherits — empty where the
// realm is in development mode and the policy is not enforced. Lower-cased.
async function requirementFor(db, codec, realm, base) {
  log.debug("Entering requirementFor().");
  const realms = require('../common/realms');
  const attributePolicy = require('../common/attribute_policy');
  const held = new Map();
  const read = async function (id, baseDn, ou) {
    log.debug("Entering read(). " + id + " " + ou);
    const parent = normalizeDn('ou=' + ou + ',' + baseDn);
    const r = await db.query('SELECT dn_key, dn, attrs FROM ' +
                             'sts_ldap_entries WHERE realm = $1 AND ' +
                             'parent_key = $2', [id, parent]);
    held.set(id + '|' + ou, (r.rows || []).map(function (row) {
      const attrs = codec.openAttributes(row.dn_key, row.attrs) || {};
      return { dn: row.dn, attributes: attrs,
               name: (attrs.cn || [])[0] ||
                     String(row.dn).split(',')[0].replace(/^cn=/i, '') };
    }));
    log.debug("Leaving read().");
  };
  await read(realm.id, base, 'attributePolicies');
  await read(realm.id, base, 'attributeDefinitions');
  if (realm.id !== realms.DEFAULT_ID) {
    await read(realms.DEFAULT_ID, realms.baseDnOf(realms.DEFAULT_ID),
               'attributePolicies');
  }
  const rowsOf = function (ou) {
    log.debug("Entering rowsOf(). " + ou);
    log.debug("Leaving rowsOf().");
    return held.get(realms.currentId() + '|' + ou) || [];
  };
  // READ-ONLY: this process writes no policy and counts nobody.
  const nothing = function () {
    log.debug("Entering nothing().");
    log.debug("Leaving nothing().");
    return false;
  };
  attributePolicy.setDirectory({
    allAttributePolicies: function () {
      log.debug("Entering allAttributePolicies().");
      log.debug("Leaving allAttributePolicies().");
      return rowsOf('attributePolicies');
    },
    writeAttributePolicy: nothing,
    deleteAttributePolicy: nothing,
    allAttributeDefinitions: function () {
      log.debug("Entering allAttributeDefinitions().");
      log.debug("Leaving allAttributeDefinitions().");
      return rowsOf('attributeDefinitions');
    },
    writeAttributeDefinition: nothing,
    deleteAttributeDefinition: nothing,
    knownName: function () {
      log.debug("Entering knownName().");
      log.debug("Leaving knownName().");
      return '';
    },
    holders: function () {
      log.debug("Entering holders().");
      log.debug("Leaving holders().");
      return 0;
    },
    missing: function () {
      log.debug("Entering missing().");
      log.debug("Leaving missing().");
      return null;
    }
  });
  const out = realms.run(realm, function () {
    return attributePolicy.enforced()
      ? attributePolicy.required().map(function (one) {
        return one.toLowerCase();
      })
      : [];
  });
  log.debug("Leaving requirementFor(). " + (out.join(', ') || 'none'));
  return out;
}

/**
 * Runs the command line.
 *
 * @param argv - the arguments after the script
 * @returns a promise of the exit code: 0 done, 3 done with records not
 *   imported (refused or taken), 1 failed or stopped, 2 usage
 */
async function main(argv) {
  log.debug("Entering main().");
  const options = optionsOf(argv);
  if (!options) {
    log.debug("Leaving main(). Usage.");
    return 2;
  }
  let pool = null;
  let driver = null;
  try {
    if (!fs.existsSync(options.file)) {
      throw refusal('STS-LDAP-0150', 'no file at ' + options.file + '.');
    }
    checkSettings();
    const persistence = require('./persistence');
    const postgres = require('./persistence_postgres');
    const keystore = require('../common/keystore');
    const realms = require('../common/realms');
    const config = require('../common/config');
    let connection;
    try {
      connection = await persistence.databaseConnection();
    } catch (e) {
      log.debug("Caught in main(): " + ((e && e.message) || e));
      throw refusal('STS-LDAP-0152', 'the database connection could not ' +
                    'be made the way the service makes it: ' +
                    ((e && e.message) || e));
    }
    const dial = postgres.dialOptions(connection.url, connection.verifyTls,
                                      connection.tlsCa);
    if (dial.refused) {
      throw refusal('STS-LDAP-0152', 'the connection string is not ' +
                    'dialled: ' + dial.refused + ' (#273).');
    }
    const Pool = /** @type {any} */ (require('pg')).Pool;
    pool = new Pool({ connectionString: dial.connectionString,
                      ssl: dial.ssl, max: 4,
                      connectionTimeoutMillis: 10000 });
    pool.on('error', function (err) {
      log.warn('bulk_import: an idle connection errored: ' +
               ((err && err.message) || err));
    });
    driver = postgres.create({ url: connection.url, log: log,
                               verifyTls: connection.verifyTls,
                               tlsCa: connection.tlsCa,
                               poolMax: postgres.poolMax(0) });
    try {
      await driver.open();
      const v = await pool.query('SELECT max(version)::int AS v FROM ' +
                                 'sts_schema');
      const version = Number(((v.rows || [])[0] || {}).v) || 0;
      if (version < MIN_SCHEMA) {
        throw new Error('the store is at schema version ' + version + ' and ' +
                        'the import needs ' + MIN_SCHEMA + ' (#623)');
      }
    } catch (e) {
      log.debug("Caught in main(): " + ((e && e.message) || e));
      throw refusal('STS-LDAP-0152', 'the store could not be opened at ' +
                    'schema version ' + MIN_SCHEMA + ' or later: ' +
                    ((e && e.message) || e));
    }
    // Asked once the schema is known to be there, and again before every
    // batch.
    await refuseWhileRunning(pool);
    const saved = await driver.loadOverrides();
    if (saved && Object.keys(saved).length) {
      config.applyPersistedOverrides(saved);
    }
    keystore.setStore(keystoreHooks(driver));
    try {
      await keystore.start();
    } catch (e) {
      log.debug("Caught in main(): " + ((e && e.message) || e));
      throw refusal('STS-LDAP-0158', 'the key-encryption key could not be ' +
                    'read, or does not open the stored keys: ' +
                    ((e && e.message) || e));
    }
    const realm = await holdRealm(pool, options.realm);
    const usersDn = 'ou=users,' + realm.base;
    // ou=users ITSELF NEED NOT BE A ROW: every process seeds the realm's
    // containers in memory at start, in both modes, and a windowed front
    // process on an empty store has been seen not to write them (#629's
    // report). The people's parent is the container every process holds.
    const codec = require('./directory_codec').create('cell');
    const language = await languageFor(pool, codec, realm.record, realm.base);
    const required = await requirementFor(pool, codec, realm.record,
                                          realm.base);
    const inRealm = function (fn) {
      log.debug("Entering inRealm().");
      log.debug("Leaving inRealm().");
      return realms.run(realm.record, fn);
    };
    const sealing = inRealm(function () {
      return keystore.persists() && keystore.sealed();
    });
    // Asked once: what this role may do to the table (#637).
    const rights = await maintenanceRights(pool);
    const merger = await namePendingMerger(pool, rights);
    const report = await importFile({
      db: pool, realmId: realm.record.id, usersDn: usersDn,
      file: options.file, batch: options.batch, skip: options.skip,
      codec: codec, sealing: sealing, language: language,
      required: required,
      // `digest` and `uuid` are asked once a record: a hot path, so no
      // Entering/Leaving pair.
      digest: function (name) {
        return inRealm(function () {
          return require('./directory_codec').lookupOf('name', name);
        });
      },
      maxEntries: function () {
        log.debug("Entering maxEntries().");
        log.debug("Leaving maxEntries().");
        return inRealm(function () {
          return Number(config.value('ldap.maxEntries')) || 0;
        });
      },
      seal: inRealm,
      afterBatch: merger.merge,
      settle: function () {
        log.debug("Entering settle().");
        log.debug("Leaving settle().");
        return keystore.settleDeks();
      },
      uuid: function () {
        return require('../common/crypto').randomUuid();
      }
    });
    report.nameIndex = merger.mode;
    if (report.imported > 0) {
      report.indexes = await settleIndexes(pool, rights);
    }
    const text = JSON.stringify(report, null, 2) + '\n';
    if (options.report) {
      fs.writeFileSync(path.resolve(options.report), text);
    } else {
      process.stdout.write(text);
    }
    log.info('bulk_import: ' + report.imported + ' imported, ' +
             report.present + ' already present, ' + report.taken +
             ' with a username held, ' + report.refused + ' refused, in ' +
             report.seconds + ' s (' + report.perSecond + ' a second).');
    log.debug("Leaving main().");
    if (report.stopped) {
      return 1;
    }
    return report.refused || report.taken ? 3 : 0;
  } catch (e) {
    log.debug("Caught in main(): " + ((e && e.message) || e));
    const message = String((e && e.message) || e);
    log.error(/^STS-/.test(message) ? message
              : errorCodes.tag('STS-LDAP-0159') + 'bulk_import: ' + message);
    log.debug("Leaving main(). Failed.");
    return 1;
  } finally {
    if (pool) {
      await pool.end().catch(function (e) {
        log.debug("Caught in main()'s pool end: " + ((e && e.message) || e));
      });
    }
    if (driver) {
      await driver.close().catch(function (e) {
        log.debug("Caught in main()'s close: " + ((e && e.message) || e));
      });
    }
  }
}

// Run when invoked, and export the pieces for the tests.
if (require.main === module) {
  main(process.argv.slice(2)).then(function (code) {
    process.exit(code);
  }, function (e) {
    log.error(errorCodes.tag('STS-LDAP-0159') + 'bulk_import: ' +
              ((e && e.stack) || e));
    process.exit(1);
  });
}

