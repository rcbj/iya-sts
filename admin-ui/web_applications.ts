  // ---------------------------------------------------------------------------
  // THE APPLICATION'S FIELD GRID (2026-09-30): the protocol families it is
  // declared for, as a row of checkboxes, and every field of
  // `applications.applicationFields()` the page can edit, typed, shown for the
