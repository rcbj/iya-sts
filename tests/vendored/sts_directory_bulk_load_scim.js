const ENTERPRISE = "urn:ietf:params:scim:schemas:extension:enterprise:2.0:User";

var http = bulk.httpFor(base, log);
var checks = bulk.checker(log);
const check = checks.check;

function scim(method, path, payload) {
  log.debug("Entering scim().");
  log.debug("Leaving scim().");
  return http.timed(base + "/scim/v2" + path, {
    method: method,
    headers: { "Content-Type": "application/scim+json",
               "Accept": "application/scim+json",
               "Authorization": SCIM_AUTH },
    body: payload === undefined ? undefined : JSON.stringify(payload)
  });
}

// ---------------------------------------------------------------------------
// THE MAPPING, READ FROM THE SERVICE.
//
// Returns { rows, sendable, dropped } — the rows this job can use, the LDAP
// attribute names it can therefore send, and the ones the catalogue offered
// that SCIM has no member for.
// ---------------------------------------------------------------------------
async function readTheMapping(catalogue) {
  log.debug("Entering readTheMapping().");
  const doc = await http.get(http.api("/scim"));
  assert.strictEqual(doc.status, 200,
    "GET /admin-api/scim answered " + doc.status + ". It publishes the " +
    "LDAP-to-SCIM attribute mapping, and this job builds every resource it " +
    "sends out of that table rather than out of a copy — see the header.");
  const published = ((doc.body && doc.body.mapping &&
                      doc.body.mapping.user) || []);
  check("the service publishes a usable User mapping", function () {
    assert.ok(published.length >= 10,
      "GET /admin-api/scim published " + published.length + " User mapping " +
      "row(s). Below ten this job cannot build a populated resource, and the " +
      "five thousand creates below would be five thousand nearly-empty " +
      "people reported as populated.");
    const complete = published.filter(function (row) {
      return row.type !== undefined && row.parent !== undefined &&
             row.extension !== undefined;
    });
    assert.strictEqual(complete.length, published.length,
      "the published mapping is missing `type`, `parent` or `extension` on " +
      (published.length - complete.length) + " row(s). Those three are what " +
      "make it usable rather than merely descriptive: two rows both map to " +
      "phoneNumbers and only `type` tells telephoneNumber from mobile, five " +
      "are members of one addresses entry, and an extension member goes " +
      "under a URN rather than at the top level. They were added to " +
      "scim/scim.js on 2026-09-06 for this job.");
  });

  const byLdap = {};
  published.forEach(function (row) {
    if (row.readOnly || row.kind === "derived") {
      return;
    }
    byLdap[String(row.ldap).toLowerCase()] = row;
  });
  const sendable = catalogue.filter(function (attribute) {
    return !!byLdap[attribute.toLowerCase()];
  });
  const dropped = catalogue.filter(function (attribute) {
    return !byLdap[attribute.toLowerCase()];
  });
  if (dropped.length) {
    // REPORTED AND NOT FAILED. RFC 7643's core schema simply has no member for
    // some of what an LDAP entry can hold, and `description` is the one this
    // catalogue offers today. Saying so is the point; the floor below is what
    // keeps that honest.
    log.warn("SCIM has no member for " + dropped.join(", ") + ", so " +
             "these people are created WITHOUT them through this door. The " +
             "other two bulk-load jobs send them. That is a fact about RFC " +
             "7643 and this service's mapping of it, not a fault, and the " +
             "read-back below checks only what was sent.");
  }
  check("SCIM can carry most of the catalogue", function () {
    assert.ok(sendable.length >= 10,
      "only " + sendable.length + " of the " + catalogue.length +
      " catalogue attribute(s) have a SCIM member in this service's mapping. " +
      "Below ten this job is not comparable with the other two doors at all.");
  });
  log.info("Sending " + sendable.length + " attribute(s) per person over " +
           "SCIM: " + sendable.join(", ") +
           (dropped.length ? " — and NOT " + dropped.join(", ") : ""));
  log.debug("Leaving readTheMapping(). " + sendable.length + " sendable.");
  return { byLdap: byLdap, sendable: sendable, dropped: dropped };
}

// Set a dotted path on an object, creating the objects on the way down.
// `name.givenName` is two levels and nothing here is deeper, but the loop is
// written for any depth because a mapping row is data and a two-level
// assumption would be this file knowing something about it that it read.
function setPath(target, path, value) {
  log.debug("Entering setPath().");
  const parts = String(path).split(".");
  let node = target;
  for (let n = 0; n < parts.length - 1; n += 1) {
    if (!node[parts[n]] || typeof node[parts[n]] !== "object") {
      node[parts[n]] = {};
    }
    node = node[parts[n]];
  }
  node[parts[parts.length - 1]] = value;
  log.debug("Leaving setPath().");
}

// ---------------------------------------------------------------------------
// ONE PERSON, AS A SCIM RESOURCE, BUILT FROM THE PUBLISHED MAPPING.
//
// Five kinds of row and each is shaped differently on the wire:
//
//   single      a member, possibly dotted (`name.givenName`)
//   multi       an array of `{value, type}` — `emails`, `phoneNumbers`
//   complex     a member of ONE entry of a multi-valued complex attribute;
//               `parent` names it, and every complex row with the same parent
//               goes into the same entry rather than one entry each
//   extension   the member goes under the extension URN rather than at the top
//   bool        not reached: nothing bulk_load.js generates maps to one
// ---------------------------------------------------------------------------
function resourceFor(person, sendable, byLdap) {
  log.debug("Entering resourceFor().");
  const resource = {
    schemas: ["urn:ietf:params:scim:schemas:core:2.0:User"],
    userName: person.username
  };
  const complexes = {};
  let usedExtension = false;
  sendable.forEach(function (attribute) {
    const row = byLdap[attribute.toLowerCase()];
    const value = bulk.FIELDS[attribute](person);
    if (row.kind === "complex") {
      const parent = row.parent || "addresses";
      complexes[parent] = complexes[parent] || {};
      // The member name is the last segment of the dotted `scim` path —
      // `addresses.streetAddress` becomes `streetAddress` inside the entry.
      complexes[parent][String(row.scim).split(".").pop()] = value;
      return;
    }
    if (row.kind === "multi") {
      const name = String(row.scim);
      resource[name] = (resource[name] || []).concat([
        row.type ? { value: value, type: row.type } : { value: value }
      ]);
      return;
    }
    if (row.extension) {
      // `scim` carries the whole URN plus the member (`urn:…:User:department`,
      // and `urn:…:User:manager.value` for the one nested member), so the split
      // is at the URN rather than at the last colon of everything.
      const member = String(row.scim).slice(ENTERPRISE.length + 1);
      resource[ENTERPRISE] = resource[ENTERPRISE] || {};
      setPath(resource[ENTERPRISE], member, value);
      usedExtension = true;
      return;
    }
    setPath(resource, String(row.scim), value);
  });
  Object.keys(complexes).forEach(function (parent) {
    // ONE ENTRY, marked `work`. A SCIM address is multi-valued and this person
    // has one; sending five entries of one member each would be five addresses
    // with one line apiece, which is a different resource that happens to
    // contain the same strings.
    resource[parent] = [Object.assign({ type: "work" }, complexes[parent])];
  });
  if (usedExtension) {
    // REQUIRED BY RFC 7643 section 3: a resource carrying an extension has to
    // declare the extension's URN in `schemas`. Added only when one was used,
    // so a mapping that stopped having extension rows does not leave this job
    // declaring a schema it sends nothing for.
    resource.schemas = resource.schemas.concat([ENTERPRISE]);
  }
  log.debug("Leaving resourceFor().");
  return resource;
}

// ---------------------------------------------------------------------------
// 1. FIVE THOUSAND PEOPLE.
// ---------------------------------------------------------------------------
async function createThePeople(sendable, byLdap) {
  log.debug("Entering createThePeople().");
  log.info("=== Creating " + SIZES.USERS + " people over SCIM in the default " +
           "realm ===");

  const watch = bulk.Stopwatch("users.create [scim]").begin();
  const created = [];
  const failures = [];

  for (let i = 1; i <= SIZES.USERS; i += 1) {
    const person = bulk.personAt(STAMP, i);
    const reply = await scim("POST", "/Users",
                             resourceFor(person, sendable, byLdap));
    watch.lap(reply.ms);
    if ((reply.status === 201 || reply.status === 200) && reply.body &&
        reply.body.id) {
      created.push({ username: person.username, dn: reply.body.id });
    } else if (failures.length < 5) {
      // THE FIRST FIVE, WHOLE. Five thousand identical refusals in a log is a
      // wall nobody reads, and the interesting information is in the first one;
      // the count below is what says how many there were.
      failures.push(person.username + " -> " + reply.status + " " +
                    String(reply.text).slice(0, 300));
    }
    if (i % 500 === 0) {
      const so_far = bulk.summaryOf(watch);
      log.info("  " + i + "/" + SIZES.USERS + " created — mean " +
               bulk.ms(so_far.meanMs) + ", median " +
               bulk.ms(so_far.medianMs) + ", " +
               so_far.perSecond.toFixed(1) + "/s");
    }
  }
  watch.end();

  check("every create was accepted", function () {
    assert.strictEqual(created.length, SIZES.USERS,
      created.length + " of " + SIZES.USERS + " SCIM creates were accepted. " +
      "The first few refusals were:\n  " + failures.join("\n  ") + "\nA " +
      "partial run makes every number below an average over a different " +
      "population than the one it claims, which is why this is asserted " +
      "rather than reported.");
  });
  // `dn` on each row is the SCIM id the create returned, which is the
  // person's entryUUID since 2026-09-14; the membership writes below send it
  // as a member value and the service stores the DN it names.
  check("every created person came back with an id, and it is their " +
        "entryUUID", function () {
    const wrong = created.filter(function (one) {
      return !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/
        .test(String(one.dn));
    });
    assert.strictEqual(wrong.length, 0,
      "the SCIM id of a person here is their directory entry's entryUUID " +
      "(RFC 4530) — `scim/CLAUDE.md` says so, and the membership writes " +
      "below send it. " + wrong.length + " came back with something else, " +
      "e.g. " + JSON.stringify(wrong.slice(0, 3)));
  });

  const summary = bulk.summaryOf(watch);
  log.info("[users] " + SIZES.USERS + " created over SCIM in " +
           (summary.wallMs / 1000).toFixed(1) + "s — mean " +
           bulk.ms(summary.meanMs) + ", median " + bulk.ms(summary.medianMs));
  log.debug("Leaving createThePeople().");
  return { people: created, summary: summary };
}

