// 2. FIFTY GROUPS.
// ---------------------------------------------------------------------------
async function createTheGroups() {
  log.debug("Entering createTheGroups().");
  log.info("=== Creating " + SIZES.GROUPS + " groups over SCIM ===");

  const watch = bulk.Stopwatch("groups.create [scim]").begin();
  const created = [];
  const failures = [];

  for (let g = 1; g <= SIZES.GROUPS; g += 1) {
    const displayName = bulk.groupNameAt(STAMP, g);
    const reply = await scim("POST", "/Groups", {
      schemas: ["urn:ietf:params:scim:schemas:core:2.0:Group"],
      displayName: displayName,
      // NO MEMBERS AT CREATE, deliberately. The membership writes are the third
      // thing being measured and folding a hundred of them into the create
      // would time one operation and report two.
      members: []
    });
    watch.lap(reply.ms);
    if ((reply.status === 201 || reply.status === 200) && reply.body &&
        reply.body.id) {
      created.push({ displayName: displayName, id: reply.body.id });
    } else if (failures.length < 5) {
      failures.push(displayName + " -> " + reply.status + " " +
                    String(reply.text).slice(0, 300));
    }
  }
  watch.end();

  check("every group was created", function () {
    assert.strictEqual(created.length, SIZES.GROUPS,
      created.length + " of " + SIZES.GROUPS + " groups were created. The " +
      "first few refusals were:\n  " + failures.join("\n  "));
  });
  check("each group came back with an id, and it is its entryUUID",
        function () {
    const wrong = created.filter(function (one) {
      return !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/
        .test(String(one.id));
    });
    assert.strictEqual(wrong.length, 0,
      "the SCIM id of a group here is its directory entry's entryUUID " +
      "(RFC 4530), which a rename does not change — it was the DN until " +
      "2026-09-14. " + wrong.length + " came back with something else, e.g. " +
      JSON.stringify(wrong.slice(0, 3)));
  });

  const summary = bulk.summaryOf(watch);
  log.info("[groups] " + SIZES.GROUPS + " created in " +
           (summary.wallMs / 1000).toFixed(1) + "s — mean " +
           bulk.ms(summary.meanMs) + ", median " + bulk.ms(summary.medianMs));
  log.debug("Leaving createTheGroups().");
  return { groups: created, summary: summary };
}

// ---------------------------------------------------------------------------
// 3. A HUNDRED PEOPLE INTO EACH GROUP, ONE AT A TIME.
//
// ONE PATCH PER MEMBERSHIP AND NOT ONE PUT PER GROUP, which is the decision
// that makes this section worth the minutes it costs. A single write carrying a
// hundred members would measure the same thing the group create measures; what
// a provisioning client actually does — SCIM, SCIM Bulk, an LDAP modify per
// user — is one write per membership, and each of those rewrites a member list
// that is one longer than the last. If this service ever gets slower as a group
// fills, THIS is the number that shows it, which is why the per-group mean is
// logged beside the overall one.
// ---------------------------------------------------------------------------
async function addTheMembers(people, groups) {
  log.debug("Entering addTheMembers().");
  log.info("=== Adding " + SIZES.PER_GROUP + " people to each of " +
           groups.length + " groups (" + (SIZES.PER_GROUP * groups.length) +
           " membership writes) over SCIM ===");

  const watch = bulk.Stopwatch("group.add-member [scim]").begin();
  const failures = [];
  const expected = {};
  let written = 0;

  for (let g = 0; g < groups.length; g += 1) {
    const group = groups[g];
    // A BLOCK PER GROUP, so every person is in EXACTLY ONE group. That is what
    // makes the read-back below an exact claim: a group holding a hundred and
    // one members, or a person in two groups, is then a defect rather than an
    // arrangement this file chose.
    const block = people.slice(g * SIZES.PER_GROUP, (g + 1) * SIZES.PER_GROUP);
    const perGroup = [];
    for (const person of block) {
      const reply = await scim("PATCH", "/Groups/" +
                               encodeURIComponent(group.id), {
        schemas: ["urn:ietf:params:scim:api:messages:2.0:PatchOp"],
        Operations: [{ op: "add", path: "members",
                       value: [{ value: person.dn }] }]
      });
      watch.lap(reply.ms);
      perGroup.push(reply.ms);
      if (reply.status === 200 || reply.status === 204) {
        written += 1;
        expected[group.id] = (expected[group.id] || 0) + 1;
      } else if (failures.length < 5) {
        failures.push(group.displayName + " += " + person.username + " -> " +
                      reply.status + " " + String(reply.text).slice(0, 300));
      }
    }
    if ((g + 1) % 10 === 0 || g === groups.length - 1) {
      const mean = perGroup.reduce(function (n, one) { return n + one; }, 0) /
          (perGroup.length || 1);
      const so_far = bulk.summaryOf(watch);
      log.info("  " + (g + 1) + "/" + groups.length + " groups filled — this " +
               "group's mean " + bulk.ms(mean) + ", overall mean " +
               bulk.ms(so_far.meanMs) + ", " + written + " membership(s) " +
               "written");
    }
  }
  watch.end();

  check("every membership write was accepted", function () {
    assert.strictEqual(written, SIZES.PER_GROUP * groups.length,
      written + " of " + (SIZES.PER_GROUP * groups.length) + " membership " +
      "writes were accepted. The first few refusals were:\n  " +
      failures.join("\n  "));
  });

  const summary = bulk.summaryOf(watch);
  log.info("[members] " + written + " memberships in " +
           (summary.wallMs / 1000).toFixed(1) + "s — mean " +
           bulk.ms(summary.meanMs) + ", median " + bulk.ms(summary.medianMs));
  log.debug("Leaving addTheMembers().");
  return { summary: summary, expected: expected };
}

// ---------------------------------------------------------------------------
// 4. READ IT BACK, THROUGH THE OTHER DOOR.
//
// The writes went in over SCIM; one half of the read-back comes out of
// `/admin-api/ldap/directory` — the service showing its own STORE — and the
// other out of `/admin-api/groups`. That is the rule
// `sts_admin_api_operations.js` states and the reason this job is a test: a
// handler that answers `{ok: true}` and writes nothing produces exactly the
// timings above, and they would look like the fastest run this service has ever
// had.
// ---------------------------------------------------------------------------
async function itReadsBackWhatItWrote(people, groups, sendable, expected) {
  log.debug("Entering itReadsBackWhatItWrote().");
  log.info("=== Reading back a sample of the people, and every group ===");

  // THE SAMPLE IS SPREAD RATHER THAN TAKEN FROM THE FRONT. A store that stopped
  // writing halfway through would pass a check of the first twenty five
  // entries, and that is precisely the failure this is here for.
  const step = Math.max(1, Math.floor(people.length / SIZES.SAMPLE));
  const sampled = [];
  for (let i = 0; i < people.length &&
                  sampled.length < SIZES.SAMPLE; i += step) {
    sampled.push(people[i]);
  }

  let missing = 0;
  const wrongValues = [];
  for (const person of sampled) {
    const reply = await scim("GET", "/Users/" + encodeURIComponent(person.dn));
    if (reply.status !== 200 || !reply.body) {
      missing += 1;
      continue;
    }
    if (reply.body.userName !== person.username) {
      wrongValues.push(person.dn + " reads back as userName=" +
                       JSON.stringify(reply.body.userName));
    }
  }
  check("the sampled people are all in the directory", function () {
    assert.strictEqual(missing, 0,
      missing + " of " + sampled.length + " sampled people could not be read " +
      "back at GET /scim/v2/Users/<dn>, spread across the whole run. A " +
      "create that answered 201 and stored nothing is the defect that makes " +
      "every timing above meaningless.");
    assert.deepStrictEqual(wrongValues, [],
      "and each must read back under the username it was created with.");
  });

  // ONE FULL ENTRY, READ OUT OF THE DIRECTORY ITSELF, so that the attributes
  // this job filled are asserted where they are STORED rather than through the
  // very mapping that wrote them — which could be inventing them on the way
  // back out just as consistently as it dropped them on the way in.
  const one = sampled[Math.floor(sampled.length / 2)];
  const entry = await http.get(http.api("/ldap/directory?q=" +
                                        encodeURIComponent(one.username) +
                                        "&per=5"));
  check("a person's entry carries the fields this job sent", function () {
    assert.strictEqual(entry.status, 200,
      "GET /admin-api/ldap/directory answered " + entry.status + ".");
    const rows = (entry.body && entry.body.entries) || [];
    // `one.dn` is the SCIM id, which is the entry's `entryUUID` since
    // 2026-09-14 and no longer its DN — so the row is the one whose own
    // `entryUUID` attribute is that id. The DN comparison is kept beside it
    // for a service from before the change, where the id was the DN.
    const found = rows.filter(function (row) {
      const attributes = row.attributes || {};
      const uuid = Object.keys(attributes).filter(function (name) {
        return name.toLowerCase() === "entryuuid";
      }).map(function (name) {
        return [].concat(attributes[name]).map(String);
      })[0] || [];
      return uuid.indexOf(one.dn) >= 0 ||
             String(row.dn || "").toLowerCase() === one.dn.toLowerCase();
    })[0];
    assert.ok(found,
      "the entry at " + one.dn + " is not in the directory's own view of " +
      "itself, searching for " + one.username + ". It answered with " +
      rows.length + " row(s).");
    // The attribute names come back in the directory's canonical spelling and
    // the values as arrays, so the comparison is case-insensitive on the name
    // and membership on the values — not because the shape is uncertain, but
    // because asserting a shape this job does not own would fail on a change
    // that is nobody's defect.
    const attributes = found.attributes || {};
    const held = {};
    Object.keys(attributes).forEach(function (name) {
      held[name.toLowerCase()] = [].concat(attributes[name]);
    });
    const person = bulk.personAt(STAMP,
                                 Number(one.username.split("-").pop()));
    const wanted = bulk.attributesFor(person, sendable);
    const wrong = [];
    Object.keys(wanted).forEach(function (name) {
      const values = held[name.toLowerCase()] || [];
      if (values.indexOf(wanted[name]) < 0) {
        wrong.push(name + ": sent " + JSON.stringify(wanted[name]) +
                   ", holds " + JSON.stringify(values));
      }
    });
    assert.deepStrictEqual(wrong, [],
      "THE ENTRY DOES NOT HOLD WHAT THE SCIM CREATE WAS SENT. Every " +
      "attribute in this list has a member in the mapping this job read from " +
      "the service, so a value that did not land was accepted and dropped " +
      "somewhere between the resource and the store — which no status code " +
      "shows:\n  " + wrong.join("\n  "));
    // ONLY WHAT WAS SENT IS CHECKED, and never that nothing else is there:
    // this door INVENTS the rest (see the header), so an entry carrying
    // twenty-five attributes when nineteen were sent is this service working
    // as designed.
  });

  // EVERY GROUP, not a sample: there are only fifty of them, the counts are the
  // whole claim of section 3, and `danglingCount` is the one field that can
  // tell "a hundred members" from "a hundred member VALUES, some of which name
  // nobody" — which is what a membership written from a DN this job got wrong
  // would look like.
  const wrongCounts = [];
  for (const group of groups) {
    const reply = await http.get(http.api("/groups?group=" +
                                          encodeURIComponent(group.id)));
    const held = (reply.body && reply.body.group) || {};
    if (reply.status !== 200 || held.memberCount !== SIZES.PER_GROUP ||
        held.presentCount !== SIZES.PER_GROUP || held.danglingCount !== 0) {
      wrongCounts.push(group.displayName + " -> " + reply.status +
                       " memberCount=" + held.memberCount +
                       " presentCount=" + held.presentCount +
                       " danglingCount=" + held.danglingCount +
                       " (expected " + (expected[group.id] || 0) + " written)");
    }
  }
  check("every group holds exactly its hundred, and all of them resolve",
        function () {
    assert.deepStrictEqual(wrongCounts, [],
      "these groups do not hold what was written into them. `memberCount` is " +
      "the values on the entry, `presentCount` how many of them name an " +
      "entry this directory holds, and a difference between the two is a " +
      "dangling member — which is what a membership written from the wrong " +
      "DN produces, silently, with a 200 on the way in:\n  " +
      wrongCounts.join("\n  "));
  });

  log.info("[read-back] OK — " + sampled.length + " people sampled across " +
           "the run, one entry checked attribute by attribute, and all " +
           groups.length + " groups hold exactly " + SIZES.PER_GROUP +
           " members that resolve.");
  log.debug("Leaving itReadsBackWhatItWrote().");
}

// ---------------------------------------------------------------------------
// THE RUN.
// ---------------------------------------------------------------------------
async function test() {
  log.debug("Entering test().");
  log.info("Filling the DEFAULT realm's directory at " + base + " with " +
           SIZES.USERS + " people, " + SIZES.GROUPS + " groups and " +
           (SIZES.GROUPS * SIZES.PER_GROUP) + " memberships, ALL OF IT OVER " +
           "SCIM 2.0. NOTHING IS DELETED AFTERWARDS — that is deliberate, " +
           "and tests/CLAUDE.md argues it.");

  bulk.checkSizes(assert);

  const ready = await bulk.preflight({ log: log, assert: assert, http: http,
                                       checks: checks });
  await createTheCaller();
  const mapping = await readTheMapping(ready.catalogue);
  const people = await createThePeople(mapping.sendable, mapping.byLdap);
  const groups = await createTheGroups();
  const members = await addTheMembers(people.people, groups.groups);
  await itReadsBackWhatItWrote(people.people, groups.groups, mapping.sendable,
                               members.expected);
  bulk.report(log, [people.summary, groups.summary, members.summary], {
    base: base, door: "scim", doorLabel: "SCIM 2.0 (/scim/v2)",
    run: STAMP.run, prefix: STAMP.prefix, held: ready.held
  });

  log.info("LEFT BEHIND ON PURPOSE, in the default realm: " +
           people.people.length + " people at uid=" + STAMP.prefix + "-*, " +
           groups.groups.length + " groups at cn=" + STAMP.prefix + "-grp-*, " +
           "and " + (SIZES.GROUPS * SIZES.PER_GROUP) + " memberships between " +
           "them. Read them at " + base + "/admin/ldap/directory and " + base +
           "/admin/groups.");

  // A FLOOR ON THE COUNT, for the reason sts_admin_console.js gives: a section
  // that stops being called takes its assertions with it and the run still says
  // "passed", which is the one failure mode a suite cannot report about itself.
  // It is low here because this file's assertions are few and each is over
  // thousands of operations.
  assert.ok(checks.count >= 13,
    "only " + checks.count + " checks ran. This file and the shared " +
    "preflight make thirteen against a healthy service, so a count this " +
    "low means a SECTION STOPPED BEING CALLED rather than that the " +
    "work got simpler.");
  log.info(checks.count + " checks passed.");
  log.info("Test completed successfully.");
  log.debug("Leaving test().");
}

