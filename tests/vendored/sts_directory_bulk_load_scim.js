// ===========================================================================
// sts_directory_bulk_load_scim.js — FIVE THOUSAND PEOPLE, FIFTY GROUPS AND
// FIVE THOUSAND MEMBERSHIPS, ALL OF IT THROUGH SCIM 2.0.
//
// The first of THREE jobs that do the same work through three different doors
// and report how long each one took:
//
//   sts_directory_bulk_load_scim.js  this file    /scim/v2
//   sts_directory_bulk_load_ldap.js               LDAP v3 on the raw socket
//   sts_directory_bulk_load_api.js                /admin-api
//
// Everything the three have in common is in `bulk_load.js` — the sizes, the
// five thousand invented people, the stopwatch, the preflight and the report —
// so that a difference between their numbers is a difference in the DOOR and
// not in the job. What each of them owns is the door, and nothing else.
//
// This one was the original and was called `sts_directory_bulk_load.js` until
// 2026-09-06. **Its user creates went through `/admin-api` back then**, with
// only the groups and the memberships over SCIM, which is why the split into
// three began with a rename: one job driving two doors could not be compared
// with anything, including itself.
//
// What it does, in the DEFAULT realm, and none of it is undone:
//
//   1. creates 5000 people through `POST /scim/v2/Users`;
//   2. creates 50 groups through `POST /scim/v2/Groups`;
//   3. adds 100 of those people to each group, ONE AT A TIME, through
//      `PATCH /scim/v2/Groups/{id}` — 5000 membership writes, so that every
//      person is in exactly one group and every group holds exactly a hundred;
//   4. reads back a sample of the people and EVERY group, off a different door
//      from the one that wrote them;
//   5. reports, per operation, how long it took: the count, the total, the
//      MEAN, the median, p95, p99, the fastest, the slowest and the rate.
//
// ---------------------------------------------------------------------------
// IT WRITES TO THE DEFAULT REALM AND DELETES NOTHING, WHICH BREAKS THIS
// DIRECTORY'S USUAL RULE ON PURPOSE.
//
// `sts_admin_api_operations.js` argues at length that a job which writes to
// what every other job reads should do it inside a trust realm of its own.
// That reasoning is right and these three jobs are an exception to it — the
// first is `sts_delegated_permissions_example.js` — and they need their own
// three sentences rather than a reference to that one:
//
//   * **THE MEASUREMENT IS OF THE DEFAULT REALM'S DIRECTORY.** A realm is a
//     store of its own, so the numbers from a fresh empty realm are the
//     numbers of an empty directory — which is the one directory nobody runs.
//     What these jobs are for is what happens to a create when the store
//     already holds thousands of entries, and the default realm is where the
//     rest of the suite has been putting them.
//   * **THE ENTRIES ARE THE DELIVERABLE.** They are what somebody looks at
//     afterwards — `/admin/ldap/directory`, `/admin/groups`, an `ldapsearch`
//     with fifteen thousand answers — and a job that deleted them would leave
//     a number in a log and nothing to check it against.
//   * **NOTHING HERE IS DELETED, ANYWHERE, EVER.** Not the people, not the
//     groups, not the memberships, and not the realm (there is none to
//     remove). That is this suite's standing rule since 2026-09-06 and it is
//     the reason these jobs can be honest about their own leavings rather than
//     tidying them into invisibility.
//
// What pays for it: every name these jobs invent carries the DOOR and the run
// stamp (`bulk-scim-<run>-000001`), so three jobs in one suite and two runs of
// the suite never collide and a person can tell one lot of five thousand from
// another; nothing in the suite asserts a directory COUNT; and all three are
// listed LAST in `MANIFEST.js`, so the jobs that walk pages and read registers
// have all run before the store grows.
//
// ---------------------------------------------------------------------------
// THE THREE DOORS DO NOT DO THE SAME AMOUNT OF WORK, AND SAYING SO IS PART OF
// THE RESULT RATHER THAN A CAVEAT ABOUT IT.
//
// All three send the SAME nineteen or twenty attributes, generated by the same
// code, for the same five thousand people. What differs is what each door does
// IN ADDITION, and it is not a difference these jobs could remove without
// stopping being tests of the doors:
//
//   * **SCIM INVENTS THE REST.** `scim.js`'s create calls `createUser()`
//     without `invent: false`, so `vc_claims.js` makes up every attribute the
//     resource did not carry and writes it onto the entry. That is what a SCIM
//     client actually gets here, and it is real work this door does per person.
//   * **THE LDAP `add` INVENTS NOTHING** and registers nobody: it is
//     `putEntry()` and an audit row.
//   * **`/admin-api` DOES EITHER**, and that job sends `invent: false` — which
//     is what the console's own New user form sends.
//
// So the honest comparison is not "SCIM is slower than LDAP" but "a person
// arriving through SCIM costs this, and a person arriving through an ldapadd
// costs that". The read-back below asserts that every attribute SENT is on the
// entry and never that nothing else is, which is what lets one assertion serve
// all three.
//
// ---------------------------------------------------------------------------
// THE LDAP-TO-SCIM MAP IS READ, NOT WRITTEN DOWN.
//
// `bulk_load.js` generates a person as LDAP attribute names, because that is
// the vocabulary two of the three doors speak natively. This one has to send
// them as SCIM members, and the translation is not mechanical: `emails` and
// `phoneNumbers` are multi-valued with a `type`, five attributes are members of
// one `addresses` entry, and four live under the enterprise extension URN.
//
// **That table is `scim/scim_map.js`'s and this job READS it**, from
// `GET /admin-api/scim`, exactly as the preflight reads the attribute catalogue
// from `GET /admin-api/users/new`. A copy in here would be a second definition
// of the mapping that would drift, and the drift would show up as five thousand
// creates quietly dropping an attribute — which no status code reports.
//
// (`type`, `parent` and `extension` were added to that published document on
// 2026-09-06 BECAUSE OF THIS JOB. Before that the table said `phoneNumbers`
// twice with nothing to tell the two rows apart, and a client reading it could
// describe the mapping and not use it.)
//
// **ONE ATTRIBUTE HAS NO SCIM MEMBER AT ALL** — `description`, which the
// management API's catalogue offers and RFC 7643 has no home for. It is
// dropped, the drop is REPORTED with the reason, and the read-back checks only
// what was sent. A job that silently sent nineteen of twenty and asserted
// twenty would fail for the right reason; one that silently sent nineteen and
// asserted nineteen would be hiding a real difference between these doors.
//
// ---------------------------------------------------------------------------
// WHAT THE TIMINGS ARE AND ARE NOT.
//
// Each figure is the wall time of ONE HTTP request/response from this process,
// measured around the `fetch`, in a job that makes them one at a time. So it
// includes the network, the TLS record layer on an already-open connection,
// this service's whole middleware stack, and the write. It is NOT a throughput
// benchmark: nothing here is concurrent, on purpose, because an average taken
// under concurrency is an average of queueing and would move with the number of
// workers rather than with the thing under test.
//
// The MEAN is the number that was asked for and the MEDIAN is the one to
// believe: a single garbage collection, a persistence flush or a worker fork
// lands in one request and moves a mean of five thousand by more than it
// deserves. Both are reported, with p95 and the maximum beside them, so that a
// run whose mean moved can be read for WHICH of those it was.
// ===========================================================================

