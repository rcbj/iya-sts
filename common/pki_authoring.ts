'use strict';
//
// File: pki_authoring.ts
//
// ===========================================================================
// THE CERTIFICATE & KEY CONFIGURATION PANE, AS A MODEL.
//
// `common/pki.js` builds this service's certificate authority and issues the
// FIXED kinds of leaf this service needs from it — signing key pairs for RFC
// 7521 and RFC 7523, TLS certificates, enrolled certificates — each to a
// profile it decides. This file is the other half: **an arbitrary
// certificate, with every field and every extension exposed**, issued from
// any authority whose private key is here.
//
// ---------------------------------------------------------------------------
// IT IS MODELLED ON THE PARENT PROJECT'S *PKI / X.509* PAGE AND IS NOT A COPY
// OF IT, AND THE DIFFERENCE DECIDES THE SHAPE OF EVERYTHING BELOW.
//
// That page is `client/public/pki.html` over `client/src/pki.js`: Web Crypto
// and pkijs IN THE BROWSER, twenty-two extension cards, live filtering as the
// profile and the cryptographic approach change. Its whole claim is that the
// key never leaves the browser.
//
// **This console is `script-src 'none'`** (every page of it but
// `/admin/api-explorer`), and this service's claim is the opposite one: the
// private keys of a certificate authority belong in the process that signs.
// So the MODEL is mirrored exactly — the same fourteen profiles, the same
// five cryptographic approaches, the same twenty-two extensions, the same
// four keystore formats, out of the same encoder — and every computation that
// page does in a browser is done here instead:
//
// | On that page | Here |
// |---|---|
// | `onProfileChange()` rewrites the extension checkboxes | *Apply the profile* is a SUBMIT, and the form comes back rewritten |
// | `onPqModeChange()` filters the Key Algorithm menu | the same submit; and an impossible pair is refused by name at the issue |
// | `onIssuerChange()` narrows Signature Algorithm | the same submit |
// | `newSerial()` refills the serial after an issue | the redrawn form carries a fresh one |
// | the JWK toggle converts the two key fields | a checkbox the redraw honours, converted through the same module |
// | the Copy buttons | gone: there is no script to copy with, and a textarea selects |
// | `downloadKeys()` builds a Blob | `POST /admin/pki/export` answers with the FILE |
//
// **THE FORM IS THE STATE AND THERE IS NO DRAFT STORE.** Every field is
// re-posted by every button, so *Apply the profile* is a pure function of what
// was on the screen — which is what lets the pane work across the request
// worker pool with no affinity and leaves this service with no fourth place a
// half-finished certificate could be sitting.
//
// **THE FIELD NAMES ARE THAT PAGE'S, VERBATIM** — `pki_dn_cn`, `pki_ext_bc`,
// `pki_ku_keyCertSign`. Not decoration: the two pages are one form over one
// encoder, and a reader moving between them should be able to see that. It is
// also what makes `FIELDS` below checkable — `tests/pki_authoring.js` asserts
// that the console draws every name in it and parses every name it draws.
//
// ---------------------------------------------------------------------------
// WHAT THIS FILE OWNS AND WHAT IT DOES NOT.
//
// It owns the READING of a form: the six line-grammars, the subject, the
// extension set, the profile defaults, which algorithms an approach allows,
// and what an issue does with all of it. It owns NO STORE — the objects live
// in `pki.js`'s `pki:<realm>` keystore row, for the argument that file makes
// about there being one answer to *where does this service keep a private
// key* — and it draws NO HTML, which is `admin-ui/pki_admin.ts`'s.
//
// A LIBRARY (rule 3): it registers no route, so its position in the require
// order is not a position. It requires `config`, `pki`, `error_codes` and the
// two vendored PKI modules; none of them requires it back, so it cannot close
// a cycle.
//
// ---------------------------------------------------------------------------
// ONE COST IS REAL AND IS SAID OUT LOUD RATHER THAN DISCOVERED.
//
// Generating a post-quantum key pair is SLOW and it runs on this thread.
// `common/worker_pool.js` exists precisely because an SLH-DSA operation stops
// this process for seconds, and this file deliberately does not use it: that
// pool's job table runs `common/pq_jose.js`, which is this service's OWN
// reading of the post-quantum constructions and is deliberately independent of
// the vendored one (`pq_jose.js`'s header spends a page on why). Handing a
// key generated by one to a certificate encoder that expects the other's byte
// layout is exactly the class of defect the independence exists to expose, and
// it would be introduced here to save a console button a few seconds.
//
// So the slow algorithms are slow, and `SLOW_FAMILIES` is what the page warns
// with. In `dispatch` mode the console holds affinity to a REQUEST worker, so
// the stall is that worker's rather than the listener's — which is a genuine
// mitigation and is also not a reason to pretend the cost is gone.
//
// ---------------------------------------------------------------------------
// TYPESCRIPT, AS A CLASS (#50, 2026-09-16). `PkiAuthoring` takes the logger,
// `config`, `pki`, `error_codes`, node's `crypto` and the two vendored PKI
// modules through its constructor, as `PkiAuthoringDeps`; every function this
// file had is a method of it, and the small helpers (`textOf()`, `flagOf()`,
// `asShown()` and the rest nobody outside called) are private. The TABLES —
// `FIELDS`, `DN_FIELDS`, `PQ_MODES` and their derivatives — stay module-level
// constants built at load, exactly as before, because `FIELDS` is generated
// from the encoder's own tables at that moment; the class carries them as
// static members too. The module still exports every name it did, for
// `admin-ui/pki_admin.ts`, `mgmt-api/` and the tests. Since #50's R2 the
// composition root builds the instance (`PkiAuthoring.defaultDeps()`) and
// installs it; the module's old export names are FACADES that forward to it,
// for the JavaScript callers, and a process without the root builds a default
// when this module finishes loading.
// ===========================================================================

