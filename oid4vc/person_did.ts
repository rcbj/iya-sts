'use strict';
//
// File: person_did.ts
//
// ===========================================================================
// A did:web THIS REALM CREATES AND PUBLISHES FOR A PERSON (#1291,
// 2026-11-03).
//
// #693 let a person NAME a DID they already control; this lets the realm
// create one for them from their portal's Self-issued IDs page and publish
// its document. rcbj's four decisions on #1291 are the specification:
//
//   1. **KEY CUSTODY, ALL THREE, PER REALM** (`did.personCustody`):
//      `wallet` (the default) — the person's wallet proves its key in a
//      self-issued (SIOPv2) round trip and only the public half is
//      published; `realm` — the key is generated by `common/crypto.js` and
//      kept SEALED, never leaving the realm; `download` — the pair is
//      generated, the private key handed over ONCE and only the public half
//      kept.
//   2. **A RANDOM IDENTIFIER**: `did:web:<host>[:realm:<id>]:users:<rid>`,
//      `<rid>` 128 random bits in base64url, so nobody enumerates accounts
//      by probing addresses and two DIDs of one person are not linkable.
//   3. **DEACTIVATE, KEEP THE URL**: removed by the person, deactivated by an
//      administrator, or the account disabled, the address answers 410 Gone
//      with `{ id, deactivated: true }`; a disabled account is decided when
//      the document is SERVED, so re-enabling the account restores it.
//   4. **A PROVED DID**: it may be preferred, released in the `did` claim,
//      and — `wallet` custody only — bind an OpenID4VCI credential.
//
// THE DESIGN, in the order a reader meets it:
//
//   * **THE DID IS FIXED AT CREATION** from the realm's public base URL and
//     stored with the record; it is never derived again from a request. In
//     product mode a base that is not pinned refuses creation
//     (`mode.mintsPersonDidsOnRequestAddress()`, STS-VC-0168): a `Host`
//     header never becomes part of a stored identifier.
//   * **STORAGE MAPS TO THE DIRECTORY**: each DID is one JSON value of
//     `stsPublishedDid` on the person's entry, withheld from LDAP reads
//     (`ldap/ldap_server.js` SECRET_ATTRIBUTES), written whole. The random
//     id finds its entry through `did.personDids`, a per-realm persisted
//     index `<rid> -> { did, sub }` (the person's `urn:uuid:` subject, which
//     outlives a rename) — one lookup, never a walk of the directory.
//   * **VERSIONS ARE APPENDED, NEVER REWRITTEN.** Every change of keys is a
//     new version: `versionId` 1..n, its `created` time, its keys, the change
//     (`create`, `add-key`, `rotate-key`) and what authorized it. DID Core's
//     `versionId` and `versionTime` are answered from that history, by the
//     document's address and by `vc_did_resolver.ts`, whose
//     `didDocumentMetadata` carries created, updated, versionId,
//     nextVersionId and deactivated. A credential bound to the DID names the
//     VERSION (`<did>?versionId=<n>#<key>`), which is what makes a did:web
//     binding sound for a DID this realm hosts: the version it names stays
//     resolvable from the realm's own history, with no fetch, for as long as
//     the history is kept — the relying party's half of #693's pin.
//   * **A CHANGE OF A `wallet` DID TAKES TWO PROOFS IN ONE ACT**: one by a
//     key the CURRENT version names (the authorization, kept as `pending`
//     for PENDING_TTL_S), and one by the new key. Both are recorded on the
//     version. A change signed only by the new key has no authorization and
//     is refused (STS-VC-0171).
//   * **THE DID IS ALSO A SELF-ISSUED SUBJECT** (`oid4vc/siop.ts`), enrolled
//     with the provenance its custody gives — `wallet`, `realm` or `issued`
//     — and the current version's keys pinned; the pin follows each new
//     version. So it can be preferred, the `did` claim releases it, a
//     `wallet` one signs in and binds credentials, and `siop.ts`'s CAEP
//     credential-change says each enrolment, re-pin and removal.
//   * **ALL CRYPTOGRAPHY IS `common/crypto.js`'s** (rule 3r): the random id,
//     the key pair, the thumbprints; the seal is `common/keystore.js`'s, as
//     an application's `didPrivateKeys` are sealed — where the key-encryption
//     key outlives the process, and as written where it does not
//     (development's ephemeral key would make it garbage after a restart).
//
// A LIBRARY with one route of its own, `GET /users/:rid/did.json`, which
// `common/protocol_stack.ts` registers beside the realm's DID documents.
// ===========================================================================

